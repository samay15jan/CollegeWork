## Contents

### C Programs
- Fundamental C programming concepts
- Lab assignments and exercises
- Compiled executable files
- Shell scripts for running multiple programs

### Python Programs
- Basic to intermediate Python exercises
- Problem-solving implementations
- Academic practice programs
- Automation scripts for execution

## Running the Programs

### C

Compile a program:

```bash
gcc filename.c -o output
./output
```

Or use the provided shell scripts where available:

```bash
./runAll.sh
```

### Python

Run an individual program:

```bash
python3 filename.py
```

Or execute all programs using:

```bash
./runAll.sh
```

